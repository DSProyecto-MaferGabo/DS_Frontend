export const t = (key: string, vars?: Record<string, string | number>) => {
  const dict = dicts[currentLanguage] || dicts['es'];
  let text = dict[key] || key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
};

export function formatDate(date: Date | string) {
  const d = typeof date === 'string' ? new Date(date) : date;
  const lang = getLanguage();
  return lang === 'en'
    ? d.toLocaleDateString('en-US')
    : d.toLocaleDateString('es-ES');
}

export function formatPrice(value: number) {
  const lang = getLanguage();
  return lang === 'en'
    ? `$${value.toFixed(2)}`
    : `${value.toFixed(2)} €`;
}

// Simple context to expose lang + t to React components
type I18nCtx = { lang: string; setLang: (l: string) => void; t: typeof t };
const I18nContext = createContext<I18nCtx | null>(null);

export const I18nProvider = ({ children }: { children: React.ReactNode }) => {
  const [langState, setLangState] = useState<string>(getLanguage());
  const setLang = (l: string) => {
    setLanguage(l);
    setLangState(l);
  };
  const value = useMemo(() => ({ lang: langState, setLang, t }), [langState]);
    return React.createElement(I18nContext.Provider, { value }, children);
};

export const useI18n = () => {
  const ctx = useContext(I18nContext);
  if (!ctx) return { lang: getLanguage(), setLang: setLanguage, t };
  return ctx;
};
