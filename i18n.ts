export const availableLanguages = [
  { code: 'es', label: 'Español' },
  { code: 'en', label: 'English' },
] as const;

const STORAGE_KEY = 'ds-lang';

function readInitialLang(): string {
  const stored = typeof window !== 'undefined' ? window.localStorage.getItem(STORAGE_KEY) : null;
  if (stored && availableLanguages.some(l => l.code === stored)) return stored;
  return 'es';
}

let currentLanguage = readInitialLang();

export function setLanguage(lang: string) {
  if (availableLanguages.some(l => l.code === lang)) {
    currentLanguage = lang;
    try { window.localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignore */ }
  }
}

export function getLanguage() {
  return currentLanguage;
}

